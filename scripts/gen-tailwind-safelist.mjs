#!/usr/bin/env node
/**
 * Generates app/tailwind-safelist.css with an explicit `@source inline(...)`
 * list of every utility candidate found in source.
 *
 * WHY: Tailwind v4 automatic content detection silently drops arbitrary-value
 * utilities (text-[13px], min-h-[88vh], shadow-[…] …) in production Turbopack
 * builds of this repo — verified against server AND export outputs while dev
 * mode was correct. Explicit @source directives did not fix it, so we force
 * generation. Run before every build (wired into package.json prebuild).
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const srcFiles = [];
function walk(dir) {
  for (const f of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, f.name);
    if (f.isDirectory()) {
      if (!/node_modules|\.next|out|\.git|\.api-static-stash/.test(p)) walk(p);
    } else if (/\.(tsx|ts)$/.test(f.name)) srcFiles.push(p);
  }
}
walk("app");
walk("components");
walk("src");
walk("lib");
walk("sanity");

const candidate = /[A-Za-z0-9_|()[\]{}.,%#/'`:+-]*[[][^[\]]+[]][A-Za-z0-9_[\]().,%#:/-]*|(?:(?:hover|focus|md|lg|sm|max-md|group-hover|peer|active|aria-|open|disabled):)*[a-z][a-z0-9-]*(?::[a-z0-9-]+)*/g;

const set = new Set();
for (const file of srcFiles) {
  const text = readFileSync(file, "utf8");
  for (const m of text.matchAll(candidate)) {
    const token = m[0];
    // Keep only plausible Tailwind candidates: contain a known prefix OR an
    // arbitrary bracket AND no spaces/slashes beyond variant prefixes.
    if (token.length < 3 || token.length > 120) continue;
    if (!/[[]/.test(token) && !/^(hover|focus|md|lg|sm|group|disabled)[:.-]/.test(token) && !/^[a-z][a-z0-9-]*$/.test(token)) continue;
    if (/\s/.test(token)) continue;
    if (/(^|[^a-z-])(true|false|undefined|null|return|if|else|import|from|const|export|typeof|await|async|new|case|break|default|function)([^a-z-]|$)/.test(token)) continue;
    if (token.startsWith("/") || token.startsWith(".") && !token.startsWith(". colloq")) continue;
    if (token.includes("//") || token.includes("http")) continue;
    set.add(token);
  }
}

// Always include the critical layout classes even if a scan edge case misses them.
for (const t of [
  "h-[calc(100dvh-4rem)]", "min-h-[88vh]", "min-h-[560px]", "min-h-[320px]",
  "max-w-[560px]", "max-w-[40ch]", "min-h-[480px]", "tnum", "kicker", "display-italic",
]) {
  if (!t.startsWith("kicker") && !t.startsWith("display")) set.add(t);
}

const list = [...set].sort();
console.log(`Found ${list.length} candidates.`);

// Escape for CSS string literal; emit in chunks to keep lines manageable.
const parts = [];
let current = [];
let currentLen = 0;
for (const t of list) {
  current.push(t);
  currentLen += t.length + 1;
  if (currentLen > 3000) {
    parts.push(current.join(" "));
    current = [];
    currentLen = 0;
  }
}
if (current.length) parts.push(current.join(" "));

const css = `/* GENERATED by scripts/gen-tailwind-safelist.mjs — do not edit.
   Regenerates on every build (prebuild + build:static). */
${parts.map((p) => `@source inline("${p}");`).join("\n")}
`;

writeFileSync("app/tailwind-safelist.css", css);
console.log("Wrote app/tailwind-safelist.css");
